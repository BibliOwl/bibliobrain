def get_response_language_instruction(language: str = "fr") -> str:
    """Return a language instruction string for the given UI language.

    Used to inject the correct output-language rule into prompts at runtime.
    """
    if language == "en":
        return (
            "Language rule: write the entire visible answer in English, the language of the question. "
            "Translate conclusions from retrieved sources when needed, but keep technical names, "
            "equation symbols and source citations unchanged."
        )
    return (
        "Regle de langue: redige toute la reponse visible en francais, la langue de la question. "
        "Traduis les conclusions issues des sources si necessaire, mais conserve les noms techniques, "
        "les symboles d'equations et les citations de sources inchanges."
    )


